'''
Writes the datasheet of an interface: the timing of each port at the device's pins, from its timing reports,
for whoever connects a part to the device.

The text for the reader is a TOML multi-line string, document, and each port is a [[pin]] table in the form of a
part file's pins, so its values can be copied into the part file of a design that connects to the device.
'''

from stacv import version
from stacv.generate import datasheet_drawing
from stacv.generate import datasheet_pin
from stacv.interface import port
from stacv.output import md5sum_table
from stacv.output import number_format

BANNER = '#' * 79
RULE = '=' * 79
FIRST_PORT_SECTION = 3
TEXT_WIDTH = 78
COLUMN_GAP = '  '
HEADER_KEYS = ['Tool Version', 'Design', 'Device', 'Speed File']


class DatasheetInputs():
    '''
    What the datasheet is written from: the interface, its files, and each port's timing reports.
    '''

    def __init__(self, sInterfaceFile, oInterface):
        self.interface_file = sInterfaceFile
        self.interface = oInterface
        # Each analyzed port's timing reports, as parsed, and the files they were read from.
        self.timing_reports = {}
        self.timing_report_files = []
        # The keys of the timing reports' header, such as Design, from the first timing report.
        self.header = {}


def generate_file(oInputs):
    lPins = build_pins(oInputs)
    lLines = ["document = '''"]
    lLines.extend(build_title(oInputs))
    lLines.extend(build_references(oInputs))
    lLines.extend(build_timing(oInputs, lPins))
    for oPin in lPins:
        lLines.extend(build_port_section(oPin))
    lLines.append("'''")
    lLines.append('')
    lLines.append(f'name = "{oInputs.interface.interface_name}"')
    for oPin in lPins:
        lLines.append('')
        lLines.extend(build_pin_table(oPin))
    return lLines


def build_pins(oInputs):
    lPins = []
    for oPort in oInputs.interface.get_analyzed_ports():
        if datasheet_pin.is_supported(oPort):
            oPin = datasheet_pin.build_pin(oPort, oInputs.timing_reports[oPort.name])
            oPin.section = FIRST_PORT_SECTION + len(lPins)
            lPins.append(oPin)
    datasheet_pin.number_repeated_symbols(lPins)
    return lPins


def build_title(oInputs):
    sName = oInputs.interface.interface_name
    sDesign = oInputs.header.get('Design', 'unknown')
    lLines = [BANNER, f'#  {sName} Interface Datasheet', BANNER, '']
    lLines.append(f'This file is the datasheet of the {sName} interface of the {sDesign} design.')
    lLines.append(f'Generated by stacv version {version.VERSION} from the timing reports of the design.')
    lLines.append('')
    lLines.append(f'  Design:   {sDesign}')
    lLines.append(f'  Device:   {format_device(oInputs.header)}')
    lLines.append(f'  Tool:     {format_tool(oInputs.header)}')
    lLines.append(f'  Corners:  {", ".join(find_process_corners(oInputs))}'.rstrip())
    lLines.append('')
    return lLines


def format_device(dHeader):
    # The speed file starts with the speed grade: -2I  PRODUCTION 1.16 2018-06-13
    sDevice = dHeader.get('Device', 'unknown')
    lSpeed = dHeader.get('Speed File', '').split()
    if len(lSpeed) == 0:
        return sDevice
    return f'{sDevice}, speed {lSpeed[0]}'


def format_tool(dHeader):
    # The tool version starts with the tool and its version: Vivado v.2020.2 (win64) Build 3064766 ...
    lWords = dHeader.get('Tool Version', 'unknown').split()
    return ' '.join(lWords[:2])


def find_process_corners(oInputs):
    # In the order the timing reports first give them.
    lCorners = []
    for oTimingReports in oInputs.timing_reports.values():
        for oTimingReport in oTimingReports.reports:
            if oTimingReport.process_corner not in lCorners:
                lCorners.append(oTimingReport.process_corner)
    return lCorners


def build_section_heading(sNumber, sTitle):
    return [RULE, f'{sNumber}  {sTitle}', RULE, '']


def build_references(oInputs):
    lFiles = [oInputs.interface_file, oInputs.interface.part, oInputs.interface.traces]
    lFiles.extend(oInputs.timing_report_files)
    lLines = build_section_heading('1', 'References')
    for sLine in md5sum_table.build_md5sum_table(lFiles):
        lLines.append('  ' + sLine)
    lLines.append('')
    return lLines


def build_timing(oInputs, lPins):
    lLines = build_section_heading('2', 'Timing')
    if len(lPins) == 0:
        lLines.extend(['No port of the interface is in this datasheet.', ''])
    else:
        lLines.extend(build_timing_table(lPins))
        lLines.append('')
        lLines.extend(build_timing_notes(oInputs, lPins))
    lLines.extend(build_ports_left_out(oInputs))
    return lLines


def build_timing_table(lPins):
    iPinWidth = find_pin_width(lPins)
    iSymbolWidth = find_symbol_width(lPins)
    iValueWidth = find_value_width(lPins)
    sSeparator = '  ' + COLUMN_GAP.join(['-' * iPinWidth, '-' * iSymbolWidth, '-' * iValueWidth, '----'])
    lLines = []
    lLines.append('  ' + COLUMN_GAP.join([f'{"Pin":<{iPinWidth}}', f'{"Parameter":<{iSymbolWidth}}', f'{"Value":^{iValueWidth}}', 'Unit']))
    lLines.append(sSeparator)
    for oPin in lPins:
        if oPin is not lPins[0]:
            lLines.append(sSeparator)
        lLines.extend(build_timing_rows(oPin, iPinWidth, iSymbolWidth, iValueWidth))
    return lLines


def build_timing_rows(oPin, iPinWidth, iSymbolWidth, iValueWidth):
    lLines = []
    sPinName = oPin.port.name
    for oParameter in oPin.parameters:
        lLines.append('  ' + COLUMN_GAP.join([f'{sPinName:<{iPinWidth}}', f'{oParameter.symbol:<{iSymbolWidth}}', f'{format_value(oParameter.value):>{iValueWidth}}', 'ns']))
        sPinName = ''
    return lLines


def find_pin_width(lPins):
    iWidth = len('Pin')
    for oPin in lPins:
        iWidth = max(iWidth, len(oPin.port.name))
    return iWidth


def find_symbol_width(lPins):
    iWidth = len('Parameter')
    for oPin in lPins:
        for oParameter in oPin.parameters:
            iWidth = max(iWidth, len(oParameter.symbol))
    return iWidth


def find_value_width(lPins):
    iWidth = 7
    for oPin in lPins:
        for oParameter in oPin.parameters:
            iWidth = max(iWidth, len(format_value(oParameter.value)))
    return iWidth


def format_value(fValue):
    return f'{fValue:.3f}'


def build_timing_notes(oInputs, lPins):
    lLines = []
    lLines.append(f'Every time is at the device\'s pins, against the edge of {describe_clock_ports(lPins)} at its pin.')
    lLines.append(f'Each value is the worst of the {join_words(find_process_corners(oInputs))} process corners.')
    for sClockPort in find_clock_ports_moved_between_edges(lPins):
        lLines.extend(wrap(f'The rising and falling edges of {sClockPort} are assumed to leave the device with the same delay.'))
    lLines.append('')
    lLines.extend(wrap('In the drawings, # is where the signal may change, and each X is a limit that a symbol gives.'))
    lLines.append('')
    return lLines


def describe_clock_ports(lPins):
    lClockPorts = find_clock_ports(lPins)
    if len(lClockPorts) == 1:
        return lClockPorts[0]
    return f'its clock ({", ".join(lClockPorts)})'


def find_clock_ports(lPins):
    lClockPorts = []
    for oPin in lPins:
        if oPin.clock_port not in lClockPorts:
            lClockPorts.append(oPin.clock_port)
    return lClockPorts


def find_clock_ports_moved_between_edges(lPins):
    lClockPorts = []
    for oPin in lPins:
        if oPin.moves_between_edges and oPin.clock_port not in lClockPorts:
            lClockPorts.append(oPin.clock_port)
    return lClockPorts


def join_words(lWords):
    if len(lWords) == 1:
        return lWords[0]
    return ', '.join(lWords[:-1]) + ' and ' + lWords[-1]


def build_ports_left_out(oInputs):
    # Every port of the interface is accounted for: a port with no section here is listed with the reason.
    lRows = []
    for oPort in oInputs.interface.ports:
        sReason = find_reason_left_out(oPort)
        if sReason is not None:
            lRows.append((oPort.name, sReason))
    if len(lRows) == 0:
        return []
    iWidth = 0
    for sName, sReason in lRows:
        iWidth = max(iWidth, len(sName))
    lLines = ['These ports are not in this datasheet:', '']
    for sName, sReason in lRows:
        lLines.append(f'  {sName:<{iWidth}}  {sReason}')
    lLines.append('')
    return lLines


def find_reason_left_out(oPort):
    if oPort.status == port.DEFER:
        return 'deferred'
    if not datasheet_pin.is_supported(oPort):
        return f'{oPort.methodology}, which stacv cannot write a datasheet for yet'
    return None


def build_port_section(oPin):
    lLines = build_section_heading(str(oPin.section), oPin.port.name)
    if oPin.port.methodology == 'SDR-SS-O':
        lLines.extend(build_output_section(oPin))
    elif oPin.port.methodology == 'SDR-SS-O-FLC':
        lLines.extend(build_first_last_clock_section(oPin))
    else:
        lLines.extend(build_round_trip_section(oPin))
    return lLines


def build_output_section(oPin):
    sCaptureEdge = datasheet_pin.find_capture_edge(oPin.port).lower()
    lLines = wrap(f'The data changes after each {oPin.edge.lower()} edge of {oPin.clock_port}, and is captured on the {sCaptureEdge} edge.')
    lLines.append('')
    lMarkers = [build_marker(oPin, 'cko_min', 1), build_marker(oPin, 'cko_max', 1)]
    lStates = [datasheet_drawing.VALID, datasheet_drawing.CHANGING, datasheet_drawing.VALID]
    lLines.extend(draw(oPin, lMarkers, lStates))
    lLines.append('')
    return lLines


def build_first_last_clock_section(oPin):
    lLines = wrap(f'A chip select, timed to the first and last {oPin.edge.lower()} edges of {oPin.clock_port}, which stops between transfers.')
    lLines.append('')
    lStates = [datasheet_drawing.CHANGING, datasheet_drawing.VALID]
    lLines.extend(draw(oPin, [build_marker(oPin, 'valid_before', -1)], lStates))
    lLines.append('')
    lStates = [datasheet_drawing.VALID, datasheet_drawing.CHANGING]
    lLines.extend(draw(oPin, [build_marker(oPin, 'valid_after', 1)], lStates))
    lLines.append('')
    return lLines


def build_round_trip_section(oPin):
    sLaunchEdge = oPin.launch_edge.lower()
    sText = f'The part launches the data on each {sLaunchEdge} edge of {oPin.clock_port}, and the device captures it with its own clock, {number_format.format_number(oPin.capture_time)} ns after that {sLaunchEdge} edge at its pins.  '
    sText += f'The device needs the data stable from {format_value(oPin.valid_from)} ns to {format_value(oPin.valid_until)} ns after the {sLaunchEdge} edge that launched it:'
    lLines = wrap(sText)
    lLines.append('')
    lMarkers = [build_marker(oPin, 'setup', -1), build_marker(oPin, 'hold', 1)]
    lStates = [datasheet_drawing.CHANGING, datasheet_drawing.VALID, datasheet_drawing.CHANGING]
    lLines.extend(draw(oPin, lMarkers, lStates))
    lLines.append('')
    return lLines


def build_marker(oPin, sKey, iDirection):
    # A value before the edge, such as a setup, is drawn at minus the value.
    oParameter = oPin.get_parameter(sKey)
    return datasheet_drawing.Marker(oParameter.symbol, round(iDirection * oParameter.value, 3))


def draw(oPin, lMarkers, lStates):
    oDrawing = datasheet_drawing.Drawing(oPin.clock_port, oPin.edge, oPin.port.name, lMarkers, lStates)
    return datasheet_drawing.draw(oDrawing)


def build_pin_table(oPin):
    lLines = ['[[pin]]']
    lLines.append(f'name = "{oPin.port.name}"')
    lLines.append(f'methodology = "{oPin.port.methodology}"')
    lLines.append(f'clock = {{pin = "{oPin.clock_port}", max_frequency = {number_format.format_number(oPin.max_frequency)}}}')
    lLines.append(f'{oPin.edge_key} = "{oPin.edge}"')
    for sKey in oPin.toml_keys:
        oParameter = oPin.get_parameter(sKey)
        lLines.append(f'{sKey} = {{value = {format_value(oParameter.value)}, symbol = "{oParameter.symbol}", source = "Section {oPin.section}"}}')
    return lLines


def wrap(sText):
    # Lines break between words, and the two spaces after a sentence are kept within a line.
    lLines = []
    sLine = ''
    for sWord in split_words(sText):
        if sLine != '' and len((sLine + sWord).rstrip()) > TEXT_WIDTH:
            lLines.append(sLine.rstrip())
            sLine = ''
        sLine += sWord
    lLines.append(sLine.rstrip())
    return lLines


def split_words(sText):
    # Each word keeps the spaces after it.
    lWords = []
    sWord = ''
    for iIndex, sCharacter in enumerate(sText):
        sWord += sCharacter
        if sCharacter == ' ' and (iIndex + 1 == len(sText) or sText[iIndex + 1] != ' '):
            lWords.append(sWord)
            sWord = ''
    if sWord != '':
        lWords.append(sWord)
    return lWords
