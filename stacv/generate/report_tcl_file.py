'''
Builds the Vivado script that writes the timing reports of every analyzed port.
'''

import os
import re

from stacv import version
from stacv.generate import generate_error
from stacv.generate import xdc
from stacv.interface import port
from stacv.rules import registers

BANNER = '#' * 79
MINOR_DIVIDER = '#' + '-' * 78
CORNERS = ['Slow', 'Fast']
OTHER_CORNER = {'Slow': 'Fast', 'Fast': 'Slow'}
ENVIRONMENT_VARIABLE = re.compile(r'\$\{(\w+)\}|\$(\w+)')


def generate_file(sInterfaceFile, oInterface, lArgv):
    check_one_timing_report_per_port(oInterface)
    lVariables = find_required_variables(oInterface)
    lLines = []
    lLines.extend(build_header(oInterface, lArgv, lVariables))
    lLines.extend(build_variable_checks(lVariables))
    lLines.extend(build_directory_checks(oInterface, sInterfaceFile))
    for sCorner in CORNERS:
        lLines.append('')
        lLines.extend(build_corner(sCorner, oInterface, sInterfaceFile))
    lLines.append('')
    lLines.extend(build_restore_defaults())
    return lLines


def check_one_timing_report_per_port(oInterface):
    for oPort in oInterface.get_analyzed_ports():
        iTimingReports = len(oPort.timing_reports_as_written)
        if iTimingReports != 1:
            raise generate_error.GenerateError('generate_010', oPort.name, f'has {iTimingReports} timing reports; the report script writes one file for each port')


def find_required_variables(oInterface):
    # Each variable is listed once, in the order it first appears in the report paths.
    lVariables = []
    for oPort in oInterface.get_analyzed_ports():
        for oMatch in ENVIRONMENT_VARIABLE.finditer(oPort.timing_reports_as_written[0]):
            add_new_variable(lVariables, get_variable_name(oMatch))
    return lVariables


def add_new_variable(lVariables, sVariable):
    if sVariable not in lVariables:
        lVariables.append(sVariable)


def build_header(oInterface, lArgv, lVariables):
    lLines = []
    lLines.append(BANNER)
    lLines.append('#')
    lLines.append(f'# Generated by stacv version {version.VERSION}')
    lLines.append(f'# Command:    {build_command(lArgv)}')
    lLines.append('#')
    lLines.append(MINOR_DIVIDER)
    lLines.append('#')
    lLines.append(f'# Interface:  {oInterface.interface_name}')
    lLines.append('#')
    lLines.append('# Purpose:    Creates timing reports for ports on interfaces.  These reports')
    lLines.append('#             can be analyzed by the sta-constraints-validator (stacv).  Each')
    lLines.append('#             analyzed port on the interface will have setup and hold reports')
    lLines.append('#             for each corner. Each port will have its own file.')
    lLines.append('#')
    lLines.extend(build_requires(lVariables))
    lLines.append(BANNER)
    return lLines


def build_requires(lVariables):
    if len(lVariables) == 0:
        return []
    lLines = []
    lLines.append(f'# Requires:   {lVariables[0]}')
    for sVariable in lVariables[1:]:
        lLines.append(f'#             {sVariable}')
    lLines.append('#')
    return lLines


def build_variable_checks(lVariables):
    if len(lVariables) == 0:
        return []
    lLines = ['']
    lLines.extend(build_banner('Verify Environment Variables Exist'))
    for sVariable in lVariables:
        lLines.append(f'if {{![info exists env({sVariable})]}} {{')
        lLines.append(f'    error "stacv: environment variable {sVariable} is not set"')
        lLines.append('}')
    return lLines


def build_directory_checks(oInterface, sInterfaceFile):
    # Vivado does not create directories, so they are checked before the corners are changed.
    lPorts = oInterface.get_analyzed_ports()
    if len(lPorts) == 0:
        return []
    lLines = ['']
    lLines.extend(build_banner('Verify Report Directories Exist'))
    for oPort in lPorts:
        lLines.extend(build_directory_check(oPort, sInterfaceFile))
    return lLines


def build_directory_check(oPort, sInterfaceFile):
    sDirectory = find_report_directory(oPort, sInterfaceFile)
    lLines = []
    lLines.append(f'# {oPort.name}')
    lLines.append(f'if {{![file isdirectory "{sDirectory}"]}} {{')
    lLines.append(f'    error "stacv: {oPort.name} report directory does not exist: {sDirectory}"')
    lLines.append('}')
    return lLines


def find_report_directory(oPort, sInterfaceFile):
    sPath = convert_to_tcl_path(oPort.timing_reports_as_written[0], sInterfaceFile)
    sDirectory = os.path.dirname(sPath)
    if sDirectory == '':
        return '.'
    return sDirectory


def build_command(lArgv):
    lWords = [os.path.basename(lArgv[0])]
    lWords.extend(lArgv[1:])
    return ' '.join(lWords)


def build_corner(sCorner, oInterface, sInterfaceFile):
    lLines = []
    lLines.extend(build_banner(f'{sCorner} Corner'))
    lLines.append(f'config_timing_corners -corner {sCorner} -delay_type min_max')
    lLines.append(f'config_timing_corners -corner {OTHER_CORNER[sCorner]} -delay_type none')
    for oPort in oInterface.ports:
        lLines.append('')
        lLines.append(f'# {oPort.name}')
        lLines.extend(build_port_reports(sCorner, oPort, sInterfaceFile))
    return lLines


def build_banner(sTitle):
    lLines = []
    lLines.append(BANNER)
    lLines.append(f'# {sTitle}')
    lLines.append(BANNER)
    return lLines


def build_port_reports(sCorner, oPort, sInterfaceFile):
    if oPort.status == port.DEFER:
        return ['# Deferred']
    sPath = convert_to_tcl_path(oPort.timing_reports_as_written[0], sInterfaceFile)
    lLines = []
    sPortOption = build_port_option(oPort)
    lLines.append(build_report_timing(sPortOption, '-setup', build_file_option(sCorner, sPath)))
    lLines.append(build_report_timing(sPortOption, '-hold', f'-append -file "{sPath}"'))
    return lLines


def build_file_option(sCorner, sPath):
    # The first report of a port starts its file, so reports from an earlier run are not kept.
    if sCorner == CORNERS[0]:
        return f'-file "{sPath}"'
    return f'-append -file "{sPath}"'


def build_port_option(oPort):
    # The paths of an output port end at it, and the paths of an input port start at it.
    if xdc.is_input(oPort):
        return f'-from [get_ports {xdc.format_port(oPort.name)}]'
    return f'-to [get_ports {xdc.format_port(oPort.name)}]'


def build_report_timing(sPortOption, sAnalysis, sFileOption):
    # Every path to or from the port, the worst for each set of pins, so every register that drives or captures it is reported.
    sPaths = f'-max_paths {registers.PATH_LIMIT} -nworst {registers.PATH_LIMIT} -unique_pins'
    return f'report_timing -column_style variable_width {sPortOption} {sAnalysis} {sPaths} -path full_clock_expanded {sFileOption}'


def convert_to_tcl_path(sPathAsWritten, sInterfaceFile):
    # Paths are resolved the same way check resolves them, leaving the environment variables for Tcl to read.
    # The variables do not need to be set where stacv runs, so a path that starts with one is left for Tcl to resolve.
    sTclPath = ENVIRONMENT_VARIABLE.sub(convert_to_tcl_variable, sPathAsWritten)
    if starts_with_environment_variable(sPathAsWritten):
        return sTclPath
    if os.path.isabs(sPathAsWritten):
        return sTclPath
    return os.path.normpath(os.path.join(os.path.dirname(sInterfaceFile), sTclPath))


def starts_with_environment_variable(sPath):
    oMatch = ENVIRONMENT_VARIABLE.match(sPath)
    return oMatch is not None


def convert_to_tcl_variable(oMatch):
    return f'$env({get_variable_name(oMatch)})'


def get_variable_name(oMatch):
    # Group 1 is the ${NAME} form and group 2 the $NAME form.
    sName = oMatch.group(1)
    if sName is None:
        sName = oMatch.group(2)
    return sName


def build_restore_defaults():
    lLines = []
    lLines.extend(build_banner('Restore Vivado Default'))
    lLines.append('config_timing_corners -corner Slow -delay_type min_max')
    lLines.append('config_timing_corners -corner Fast -delay_type min_max')
    return lLines
