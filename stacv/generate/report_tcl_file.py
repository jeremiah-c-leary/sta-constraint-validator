'''
Builds the Vivado script that writes the timing reports of every analyzed port.
'''

import os
import re

from stacv import version
from stacv.generate import generate_error
from stacv.interface import port

BANNER = '#' * 79
MINOR_DIVIDER = '#' + '-' * 78
CORNERS = ['Slow', 'Fast']
OTHER_CORNER = {'Slow': 'Fast', 'Fast': 'Slow'}
ENVIRONMENT_VARIABLE = re.compile(r'\$\{(\w+)\}|\$(\w+)')


def generate_file(sInterfaceFile, oInterface, lArgv):
    check_one_timing_report_per_port(oInterface)
    lLines = []
    lLines.extend(build_header(oInterface, lArgv))
    for sCorner in CORNERS:
        lLines.append('')
        lLines.extend(build_corner(sCorner, oInterface, sInterfaceFile))
    lLines.append('')
    lLines.extend(build_restore_defaults())
    return lLines


def check_one_timing_report_per_port(oInterface):
    for oPort in oInterface.get_analyzed_ports():
        iTimingReports = len(oPort.timing_reports_as_written)
        if iTimingReports != 1:
            raise generate_error.GenerateError('generate_010', oPort.name, f'has {iTimingReports} timing reports; the report script writes one file for each port')


def build_header(oInterface, lArgv):
    lLines = []
    lLines.append(BANNER)
    lLines.append('#')
    lLines.append(f'# Generated by stacv version {version.VERSION}')
    lLines.append(f'# Command:    {build_command(lArgv)}')
    lLines.append('#')
    lLines.append(MINOR_DIVIDER)
    lLines.append('#')
    lLines.append(f'# Interface:  {oInterface.interface_name}')
    lLines.append('#')
    lLines.append('# Purpose:    Creates timing reports for ports on interfaces.  These reports')
    lLines.append('#             can be analyzed by the sta-constraints-validator (stacv).  Each')
    lLines.append('#             analyzed port on the interface will have setup and hold reports')
    lLines.append('#             for each corner. Each port will have its own file.')
    lLines.append('#')
    lLines.append(BANNER)
    return lLines


def build_command(lArgv):
    lWords = [os.path.basename(lArgv[0])]
    lWords.extend(lArgv[1:])
    return ' '.join(lWords)


def build_corner(sCorner, oInterface, sInterfaceFile):
    lLines = []
    lLines.extend(build_banner(f'{sCorner} Corner'))
    lLines.append(f'config_timing_corners -corner {sCorner} -delay_type min_max')
    lLines.append(f'config_timing_corners -corner {OTHER_CORNER[sCorner]} -delay_type none')
    for oPort in oInterface.ports:
        lLines.append('')
        lLines.append(f'# {oPort.name}')
        lLines.extend(build_port_reports(sCorner, oPort, sInterfaceFile))
    return lLines


def build_banner(sTitle):
    lLines = []
    lLines.append(BANNER)
    lLines.append(f'# {sTitle}')
    lLines.append(BANNER)
    return lLines


def build_port_reports(sCorner, oPort, sInterfaceFile):
    if oPort.status == port.DEFER:
        return ['# Deferred']
    sPath = convert_to_tcl_path(oPort.timing_reports_as_written[0], sInterfaceFile)
    lLines = []
    lLines.append(build_report_timing(oPort.name, '-setup', build_file_option(sCorner, sPath)))
    lLines.append(build_report_timing(oPort.name, '-hold', f'-append -file "{sPath}"'))
    return lLines


def build_file_option(sCorner, sPath):
    # The first report of a port starts its file, so reports from an earlier run are not kept.
    if sCorner == CORNERS[0]:
        return f'-file "{sPath}"'
    return f'-append -file "{sPath}"'


def build_report_timing(sPortName, sAnalysis, sFileOption):
    return f'report_timing -column_style variable_width -to [get_ports {sPortName}] {sAnalysis} -path full_clock_expanded {sFileOption}'


def convert_to_tcl_path(sPathAsWritten, sInterfaceFile):
    # Paths are resolved the same way check resolves them, leaving the environment variables for Tcl to read.
    # The variables do not need to be set where stacv runs, so a path that starts with one is left for Tcl to resolve.
    sTclPath = ENVIRONMENT_VARIABLE.sub(convert_to_tcl_variable, sPathAsWritten)
    if starts_with_environment_variable(sPathAsWritten):
        return sTclPath
    if os.path.isabs(sPathAsWritten):
        return sTclPath
    return os.path.normpath(os.path.join(os.path.dirname(sInterfaceFile), sTclPath))


def starts_with_environment_variable(sPath):
    oMatch = ENVIRONMENT_VARIABLE.match(sPath)
    return oMatch is not None


def convert_to_tcl_variable(oMatch):
    sName = oMatch.group(1)
    if sName is None:
        sName = oMatch.group(2)
    return f'$env({sName})'


def build_restore_defaults():
    lLines = []
    lLines.extend(build_banner('Restore Vivado Default'))
    lLines.append('config_timing_corners -corner Slow -delay_type min_max')
    lLines.append('config_timing_corners -corner Fast -delay_type min_max')
    return lLines
